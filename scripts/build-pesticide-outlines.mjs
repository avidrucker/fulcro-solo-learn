#!/usr/bin/env node
// Derive resources/public/css/pesticide-outlines.css from the upstream
// node_modules/pesticide/css/pesticide.css by stripping every depth
// declaration (box-shadow, -webkit-box-shadow, background-color) and
// dropping rule blocks left empty.
//
// Upstream pesticide v1.3.0 ships `pesticide.css` as a combined
// outlines+depth sheet and `pesticide-depth.css` as depth-only, but
// no outlines-only variant. Without one, the Settings "Rainbow element
// outlines" toggle implicitly applies depth visuals too, and the
// "Depth background colors" toggle becomes a no-op. See docs/bugs.md
// B-15.
//
// Re-run after any pesticide bump; commit the regenerated output.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const SRC  = resolve(ROOT, 'node_modules/pesticide/css/pesticide.css');
const DST  = resolve(ROOT, 'resources/public/css/pesticide-outlines.css');

const DEPTH_PROP_RE = /^\s*(?:-webkit-)?(?:box-shadow|background-color)\s*:/i;

const raw = readFileSync(SRC, 'utf8')
  // Drop upstream CSS comments so the file-header comment doesn't
  // end up wedged into the first selector after we split on `}`.
  .replace(/\/\*[\s\S]*?\*\//g, '');

const out = [
  '/*',
  ' * pesticide-outlines.css — outlines-only derivation of pesticide.css.',
  ' * GENERATED by scripts/build-pesticide-outlines.mjs — do not hand-edit.',
  ' * Re-run that script after any pesticide bump. See docs/bugs.md B-15.',
  ' */',
];

let kept = 0;
let dropped = 0;

for (const chunk of raw.split('}')) {
  const openIdx = chunk.indexOf('{');
  if (openIdx === -1) continue; // trailing whitespace / leading file comment

  const selector = chunk.slice(0, openIdx).trim();
  const body     = chunk.slice(openIdx + 1);

  const keptDecls = body
    .split(';')
    .map((s) => s.trim())
    .filter((s) => s.length > 0 && !DEPTH_PROP_RE.test(s));

  if (keptDecls.length === 0) { dropped++; continue; }

  out.push('');
  out.push(`${selector} {`);
  keptDecls.forEach((decl, i) => {
    const last = i === keptDecls.length - 1;
    out.push(`  ${decl};${last ? ' }' : ''}`);
  });
  kept++;
}

writeFileSync(DST, out.join('\n') + '\n', 'utf8');
console.log(`pesticide-outlines: wrote ${DST}`);
console.log(`  kept ${kept} rule blocks, dropped ${dropped} depth-only blocks`);
